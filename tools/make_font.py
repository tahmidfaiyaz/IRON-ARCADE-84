def glyph(rows):
    pen = TTGlyphPen(None)
    # Merge adjacent pixels in a row into a single rectangle.
    for row, bits in enumerate(rows):
        col = 0
        while col < len(bits):
            if bits[col] == '0':
                col += 1
                continue
            start = col
            while col < len(bits) and bits[col] == '1':
                col += 1
            x0, x1, y0 = 50 + start * 100, 50 + col * 100, (6-row)*100
            pen.moveTo((x0,y0))
            pen.lineTo((x0,y0+100))
            pen.lineTo((x1,y0+100))
            pen.lineTo((x1,y0))
            pen.closePath()
    return pen.glyph()

def main():
    fb = FontBuilder(1000, isTTF=True)
    charmap = {ord(c): f'uni{ord(c):04X}' for c in BITMAPS}
    for c in 'abcdefghijklmnopqrstuvwxyz':
        charmap[ord(c)] = charmap[ord(c.upper())]
    charmap[0x2019] = charmap[ord("'")]
    charmap[0x2018] = charmap[ord("'")]
    charmap[0x2013] = charmap[ord('-')]
    charmap[0x2014] = charmap[ord('-')]
    charmap[0x00A0] = charmap[ord(' ')]
    glyphs = {'.notdef': glyph(['11111','10001','10101','10101','10101','10001','11111'])}
    glyphs.update({charmap[ord(c)]: glyph(rows) for c, rows in BITMAPS.items()})
    fb.setupGlyphOrder(list(glyphs))
    fb.setupCharacterMap(charmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({name: (650, 50) for name in glyphs})
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({'familyName':'Arcade84','styleName':'Regular','uniqueFontIdentifier':'IRON ARCADE 84 original bitmap 1.0','fullName':'Arcade84 Regular','psName':'Arcade84-Regular','version':'Version 1.0'})
    fb.setupOS2(sTypoAscender=800,sTypoDescender=-200,sTypoLineGap=0,usWinAscent=800,usWinDescent=200)
    fb.setupPost()
    destination = Path(__file__).resolve().parents[1] / 'assets' / 'arcade.ttf'
    destination.parent.mkdir(parents=True,exist_ok=True)
    fb.save(destination)
    print(destination)

if __name__ == '__main__':
    main()
